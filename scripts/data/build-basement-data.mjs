#!/usr/bin/env node
// Distills data/recs + data/census into lib/data/basement.json for the basement pages.
// Rerun after refreshing either dataset: node scripts/data/build-basement-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const recs = JSON.parse(readFileSync('data/recs/recs_state_feature_stats_multi_year.json', 'utf8'));
const soc = JSON.parse(readFileSync('data/census/census_soc_new_homes_by_region.json', 'utf8'));
const KEYS = ['homes_millions', 'avg_total_sqft', 'pct_basement', 'pct_basement_finished_of_basements', 'pct_finished_basement_all_homes', 'pct_basement_heated_of_basements', 'pct_owners_count_basement_in_sqft'];
const pick = (block) => {
  if (!block) return null;
  const o = {};
  for (const k of KEYS) { if (block[k] !== undefined) o[k] = block[k]; if (block[k + '_rse'] !== undefined) o[k + '_rse'] = block[k + '_rse']; }
  return o;
};
const states = {};
for (const [abbr, yrs] of Object.entries(recs.states)) {
  if (abbr === 'DC') continue;
  states[abbr] = {};
  for (const y of ['2009', '2020', '2024']) if (yrs[y]) states[abbr][y] = pick(yrs[y].sf);
}
const us = {}; for (const y of ['2009', '2015', '2020', '2024']) us[y] = pick(recs.series.US[y].sf);
const census = {};
for (const geo of ['US', 'Northeast', 'Midwest', 'South', 'West']) {
  census[geo] = Object.entries(soc.series[geo]).filter(([, v]) => v.basement_full_or_partial != null).map(([y, v]) => [Number(y), v.basement_full_or_partial]).sort((a, b) => a[0] - b[0]);
}
writeFileSync('lib/data/basement.js', '// Generated by scripts/data/build-basement-data.mjs. Do not edit.\nexport default ' + JSON.stringify({ meta: { recs: 'EIA RECS 2009/2020/2024 single-family homes, see data/recs', census: 'Census Survey of Construction, share of new single-family houses completed with a full or partial basement, see data/census', built: new Date().toISOString().slice(0, 10) }, us, states, census }) + ';\n');
console.log('states', Object.keys(states).length, 'census years', census.US.length);
